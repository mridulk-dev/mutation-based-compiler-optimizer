ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_CONFIG = os.path.join(ROOT, "benchmarks", "configs", "miniarith-v1.json")
BUILDER_VERSION = "1.0"
CAT_CODE = {"arithmetic": "ARI", "constant-heavy": "CON", "dead-code": "DEA", "common-subexpression": "CSE",
            "strength-reduction": "STR", "mixed": "MIX"}
GROUP_ORDER = {"controlled": 0, "randomized": 1, "external": 2}

PROJECT_LICENSE = {
    "status": "project-generated",
    "license": "repository license (no LICENSE file present at build time; to be chosen by the authors)",
    "note": "Generated by this project's own generator code; no third-party source.",
}


def sha256_text(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def normalize_source(source):
    """Strip comments, collapse whitespace: formatting-only changes hash equally."""
    no_comments = re.sub(r"#[^\n]*", "", source)
    tokens = re.findall(r"==|!=|<=|>=|[A-Za-z_]\w*|\d+|\S", no_comments)
    return " ".join(tokens)


def tac_text(program):
    return format_tac(program, numbered=False)


def test_vectors(cfg, pid, n_inputs, seed):
    tc = cfg["tests"]
    vecs = []
    for pattern in tc["edge_vectors"]:
        v = [pattern[k % len(pattern)] for k in range(n_inputs)]
        if v not in vecs:
            vecs.append(v)
    rng = random.Random(f"{seed}:tests:{pid}")
    lo, hi = tc["random_range"]
    for _ in range(tc["random_vectors"]):
        vecs.append([rng.randint(lo, hi) for _ in range(n_inputs)])
    return vecs


# --- candidate collection ---------------------------------------------------------
def collect_review1(cfg):
    with open(os.path.join(ROOT, cfg["review1"]["path"]), encoding="utf-8") as fh:
        data = json.load(fh)
    out = []
    for p in data["programs"]:
        out.append({
            "id": p["id"], "group": "controlled", "subgroup": "review1", "category": p["category"],
            "review1_member": True, "source": p["source"],
            "origin": {"kind": "generated", "generator": data["generator"], "generator_version": "review1",
                       "seed": data["seed"], "config": {"category_plan": data["categories"]},
                       "note": "Review-1 controlled set, imported unchanged (source, id and tests)"},
            "attribution": "Project authors (Review-1 dataset)",
            "license": PROJECT_LICENSE,
            "fixed_tests": [{"inputs": t["inputs"], "expected_outputs": t["expected_outputs"],
                             "expected_error_flag": t["expected_error"]} for t in p["tests"]],
        })
    return out


def collect_synthetic(cfg, seed):
    sc = cfg["synthetic"]
    out = []
    for cat in templates.CATEGORIES:
        for k in range(sc["per_category"]):
            size = sc["sizes"][k % len(sc["sizes"])]
            red = sc["redundancy"][(k // len(sc["sizes"])) % len(sc["redundancy"])]
            pid = f"SYN-{CAT_CODE[cat]}-{k + 1:03d}"
            out.append({
                "id": pid, "group": "controlled", "subgroup": "synthetic-template", "category": cat,
                "review1_member": False,
                "source": templates.generate_program(seed, pid, cat, size, red),
                "origin": {"kind": "generated", "generator": "benchmarks/templates.py",
                           "generator_version": templates.TEMPLATE_VERSION, "seed": f"{seed}:{pid}",
                           "config": {"size": size, "redundancy": red}},
                "attribution": "Project authors (template generator)",
                "license": PROJECT_LICENSE,
            })
    return out


def collect_random(cfg, seed):
    out = []
    for k in range(cfg["random"]["count"]):
        pid = f"RND-{k + 1:04d}"
        out.append({
            "id": pid, "group": "randomized", "subgroup": "random-grammar", "category": "random",
            "review1_member": False,
            "source": randomgen.generate_program(seed, pid),
            "origin": {"kind": "generated", "generator": "benchmarks/randomgen.py",
                       "generator_version": randomgen.RANDOM_VERSION, "seed": f"{seed}:{pid}",
                       "config": randomgen.RANDOM_CONFIG},
            "attribution": "Project authors (random generator)",
            "license": PROJECT_LICENSE,
        })
    return out


def collect_external(cfg, seed, use_gcc):
    out = []
    recs = external.extract_all(lambda f: random.Random(f"{seed}:external:{f}"), use_gcc=use_gcc)
    for k, r in enumerate(recs):
        pid = f"EXT-JOTAI-{k + 1:03d}"
        rec = {
            "id": pid, "group": "external", "subgroup": "jotai-anghaleaves", "category": "external-c",
            "review1_member": False, "source": r.get("source"),
            "origin": {
                "kind": "upstream", "collection": external.COLLECTION["name"],
                "collection_url": external.COLLECTION["url"], "local_file": f"jotai_unique_300/{r['file']}",
                "file_sha256": r["file_sha256"], "file_hash_verified": r["file_hash_verified"],
                "function": r.get("function") or r.get("function_hint"),
                "upstream_path_hint": r["upstream_path_hint"],
                "upstream_path_hint_note": "flattened path as encoded in the AnghaBench/Jotai file name; "
                                           "the originating repository boundary is not recoverable",
                "extractor": "benchmarks/external.py", "extractor_version": external.EXTRACTOR_VERSION,
                "upstream_function_source": r.get("c_function"),
            },
            "attribution": f"{external.COLLECTION['citation']} Function from an open-source project "
                           f"collected by AnghaBench (project not identified by Jotai).",
            "license": {
                "status": "unverified",
                "collection_license": external.COLLECTION["repository_license"],
                "collection_license_status": external.COLLECTION["repository_license_status"],
                "upstream_function_license": "unknown - not stated by Jotai/AnghaBench",
                "note": "The project's own tooling license does NOT apply to this function.",
            },
        }
        if r["status"] == "incompatible":
            rec["precheck"] = {"status": "incompatible", "reason": r["reason"]}
        else:
            rec["conversion"] = {
                "method": "conservative C-subset translation (see benchmarks/external.py)",
                "steps": ["extract function region from the Jotai file",
                          "tokenise and check every token against the supported C subset",
                          "parameters -> one `input` statement (declaration order)",
                          "int declarations with initialiser / assignments -> assignments; x op= e -> x = x op (e)",
                          "return e -> print e",
                          "hex/octal literals -> decimal",
                          "discard test vectors whose evaluation leaves the int32 range"],
                "limitations": ["equivalent to the C function only where C behaviour is defined "
                                "(no signed overflow, no division by zero)",
                                "C int assumed to be 32-bit"],
                "dropped_int32_vectors": r["dropped_int32_vectors"],
                "upstream_harness_cases": [{"case": c, "inputs": v} for c, v in r["upstream_cases"]],
                "crosscheck": r["crosscheck"],
            }
            rec["external_tests"] = r["tests"]
        out.append(rec)
    return out


# --- validation ---------------------------------------------------------------------
def opportunities(program):
    counts = Counter(m.op_id for m in generate_mutations(program, OPERATORS))
    return {op: counts.get(op, 0) for op, _ in OPERATORS}


def validate(rec, cfg, seed):
    """Fill in tac, hashes, tests and validation status for one candidate."""
    limits = cfg["limits"]
    checks = {}
    rec["validation"] = {"checks": checks, "status": None, "reason": None}
    if rec.get("precheck"):
        rec["status"] = "incompatible"
        rec["validation"].update(status="incompatible", reason=rec["precheck"]["reason"])
        return rec
    source = rec["source"]
    rec["source_sha256"] = sha256_text(source)
    rec["normalized_source"] = normalize_source(source)
    rec["normalized_source_sha256"] = sha256_text(rec["normalized_source"])
    try:
        ast = parse(source)
        program = TACGenerator().gen_program(ast)
        checks["parses"] = True
    except (LexError, ParseError) as exc:
        checks["parses"] = False
        return _reject(rec, "malformed", f"does not parse: {exc}")
    rec["tac"] = tac_text(program)
    rec["tac_sha256"] = sha256_text(rec["tac"])
    rec["canonical_tac_sha256"] = sha256_text(tac_text(canonical_tac(program)))
    n_in = sum(1 for i in program if i.op == "input")
    rec["n_inputs"] = n_in
    rec["n_tac_instructions"] = len(program)
    rec["n_source_statements"] = len(ast.stmts)
    rec["opportunities"] = opportunities(program)

    if rec.get("external_tests") is not None:
        vectors = [t["inputs"] for t in rec.pop("external_tests")]
    elif rec.get("fixed_tests") is not None:
        vectors = [t["inputs"] for t in rec["fixed_tests"]]
    else:
        vectors = test_vectors(cfg, rec["id"], n_in, seed)
    compiled = compile_tac(program)
    tests, ok_tac, ok_comp, int32_safe, max_abs = [], True, True, True, 0
    for v in vectors:
        ref = ast_run_detailed(ast, v)
        tac = run(program, v)
        comp = compiled(v)
        ok_tac &= tac.observable == ref.observable
        ok_comp &= comp == ref.observable
        int32_safe &= ref.int32_violations == 0
        max_abs = max(max_abs, ref.max_abs)
        tests.append({"inputs": v, "expected_outputs": list(ref.outputs), "expected_error": ref.error})
    rec["tests"] = tests
    rec["expected_outputs_from"] = "execution/reference.py (AST reference interpreter)"
    rec["int32_safe_on_tests"] = int32_safe
    checks["tac_matches_reference"] = ok_tac
    checks["compiled_matches_reference"] = ok_comp

    fixed = rec.pop("fixed_tests", None)
    if fixed is not None:  # Review-1: stored outputs must equal the independent reference
        same = all(t["expected_outputs"] == f["expected_outputs"]
                   and (t["expected_error"] is not None) == f["expected_error_flag"] for t, f in zip(tests, fixed))
        checks["review1_outputs_reproduced"] = same
        if not same:
            return _reject(rec, "reference-mismatch", "stored Review-1 outputs differ from the reference")
    if not ok_tac:
        return _reject(rec, "frontend-mismatch", "TAC interpreter disagrees with the AST reference")
    if not ok_comp:
        return _reject(rec, "backend-mismatch", "compiled backend disagrees with the AST reference")
    if not any(i.op == "print" for i in program):
        return _reject(rec, "no-output", "program prints nothing")
    if all(t["expected_error"] is not None for t in tests):
        return _reject(rec, "always-fails", "every test vector ends in a runtime error")
    if all(t["expected_error"] is not None and not t["expected_outputs"] for t in tests):
        return _reject(rec, "degenerate", "fails before producing any output")
    if max_abs > limits["max_abs_value"]:
        return _reject(rec, "magnitude-exceeds-int64", f"intermediate value magnitude {max_abs} exceeds int64")
    if len(program) > limits["max_tac_instructions"]:
        return _reject(rec, "too-large", f"{len(program)} TAC instructions")
    compute = sum(1 for i in program if i.op not in ("input", "print"))
    if compute < limits["min_compute_instructions"]:
        if rec["group"] != "external":
            return _reject(rec, "trivial", f"only {compute} non-I/O instructions")
        checks["trivial_kept_as_external"] = True
    cc = rec.get("conversion", {}).get("crosscheck")
    if cc is not None:
        checks["c_crosscheck"] = cc["status"]
        if cc["status"] in ("failed", "error"):
            return _reject(rec, "c-crosscheck-" + cc["status"], cc.get("message"))
    rec["status"] = "accepted"
    rec["validation"]["status"] = "accepted"
    return rec


def _reject(rec, code, message):
    rec["status"] = "rejected"
    rec["validation"].update(status="rejected", reason=code, message=message)
    return rec


# --- orchestration ------------------------------------------------------------------
FIELD_ORDER = ["id", "status", "group", "subgroup", "category", "review1_member", "source", "source_sha256",
               "normalized_source", "normalized_source_sha256", "tac", "tac_sha256", "canonical_tac_sha256",
               "n_inputs", "n_source_statements", "n_tac_instructions", "opportunities", "origin", "conversion",
               "attribution", "license", "tests", "expected_outputs_from", "int32_safe_on_tests", "validation",
               "duplicate_of"]


def ordered(rec):
    out = {k: rec[k] for k in FIELD_ORDER if k in rec}
    out.update({k: v for k, v in rec.items() if k not in out})
    return out


def build(cfg, use_gcc=True, log=print):
    seed = cfg["dataset_seed"]
    log(f"collecting candidates (seed {seed})")
    cands = collect_review1(cfg) + collect_synthetic(cfg, seed) + collect_random(cfg, seed)
    if cfg["external"]["jotai"]:
        cands += collect_external(cfg, seed, use_gcc and cfg["external"]["use_gcc"])
    log(f"  {len(cands)} candidates; validating")
    records = [validate(r, cfg, seed) for r in cands]
    records.sort(key=lambda r: (GROUP_ORDER[r["group"]], 0 if r["review1_member"] else 1, r["id"]))
    report = deduplicate(records)
    records = [ordered(r) for r in records]
    stats = compute_statistics(records, report)
    return records, report, stats


def manifest_text(records):
    return "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in records)


def gcc_version():
    gcc = external.find_gcc()
    if not gcc:
        return None
    try:
        return subprocess.run([gcc, "--version"], capture_output=True, text=True, timeout=30).stdout.splitlines()[0]
    except (OSError, subprocess.SubprocessError):
        return "unknown"


def write_outputs(cfg, records, report, stats, config_path):
    out_dir = os.path.join(ROOT, cfg["output_dir"])
    os.makedirs(out_dir, exist_ok=True)
    text = manifest_text(records)
    with open(os.path.join(out_dir, "manifest.jsonl"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    with open(os.path.join(out_dir, "dedup_report.json"), "w", encoding="utf-8", newline="\n") as fh:
        json.dump(report, fh, indent=2)
        fh.write("\n")
    write_statistics(stats, out_dir)
    with open(config_path, "rb") as fh:
        cfg_hash = hashlib.sha256(fh.read()).hexdigest()
    info = {
        "dataset": cfg["name"], "builder_version": BUILDER_VERSION,
        "config_path": os.path.relpath(config_path, ROOT).replace("\\", "/"), "config_sha256": cfg_hash,
        "manifest_sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
        "python": platform.python_version(), "platform": platform.platform(), "gcc": gcc_version(),
        "note": "This file records the build environment and is the only non-deterministic output.",
    }
    with open(os.path.join(out_dir, "build_info.json"), "w", encoding="utf-8", newline="\n") as fh:
        json.dump(info, fh, indent=2)
        fh.write("\n")
    return out_dir, info


def strip_crosscheck(records):
    out = []
    for r in records:
        r = json.loads(json.dumps(r))
        r.get("conversion", {}).pop("crosscheck", None)
        r.get("validation", {}).get("checks", {}).pop("c_crosscheck", None)
        out.append(r)
    return out


def check(cfg, use_gcc):
    out_dir = os.path.join(ROOT, cfg["output_dir"])
    path = os.path.join(out_dir, "manifest.jsonl")
    if not os.path.exists(path):
        print(f"no committed manifest at {path}")
        return 1
    with open(path, encoding="utf-8") as fh:
        committed = [json.loads(line) for line in fh]
    records, _, _ = build(cfg, use_gcc=use_gcc, log=lambda *_: None)
    fresh = json.loads(json.dumps(records))
    if not use_gcc or external.find_gcc() is None:
        committed, fresh = strip_crosscheck(committed), strip_crosscheck(fresh)
        # without gcc, external fragments cannot be re-cross-checked; compare everything else
        for r in committed + fresh:
            if r["group"] == "external" and r["status"] == "accepted":
                r["validation"]["checks"].pop("c_crosscheck", None)
    if committed == fresh:
        print(f"OK: rebuilt dataset is identical to {os.path.relpath(path, ROOT)} ({len(fresh)} records)")
        return 0
    diffs = [a["id"] for a, b in zip(committed, fresh) if a != b]
    print(f"MISMATCH: {len(diffs)} records differ (first: {diffs[:5]}), "
          f"committed {len(committed)} vs rebuilt {len(fresh)} records")
    return 1


def main(argv=None):
    ap = argparse.ArgumentParser(description="Build the versioned MiniArith benchmark dataset")
    ap.add_argument("--config", default=DEFAULT_CONFIG)
    ap.add_argument("--check", action="store_true", help="rebuild in memory and compare with committed files")
    ap.add_argument("--no-gcc", action="store_true", help="skip the gcc cross-check of external fragments")
    args = ap.parse_args(argv)
    with open(args.config, encoding="utf-8") as fh:
        cfg = json.load(fh)
    if args.check:
        return check(cfg, not args.no_gcc)
    records, report, stats = build(cfg, use_gcc=not args.no_gcc)
    out_dir, info = write_outputs(cfg, records, report, stats, args.config)
    s = stats["totals"]
    print(f"wrote {out_dir}")
    print(f"  manifest sha256 {info['manifest_sha256']}")
    print(f"  candidates {s['candidates']}: accepted {s['accepted']}, rejected {s['rejected']}, "
          f"duplicate {s['duplicate']}, incompatible {s['incompatible']}")
    for g, row in stats["by_group"].items():
        print(f"    {g:<11} accepted {row.get('accepted', 0):>4}  rejected {row.get('rejected', 0):>3}  "
              f"duplicate {row.get('duplicate', 0):>3}  incompatible {row.get('incompatible', 0):>3}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
