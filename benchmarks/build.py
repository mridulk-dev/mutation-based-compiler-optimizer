"""Build, validate, deduplicate and describe a versioned MiniArith dataset.

    python -m benchmarks.build                         # build dataset/miniarith-v1 from its config
    python -m benchmarks.build --check                 # rebuild in memory, compare with committed files
    python -m benchmarks.build --no-gcc                # skip the C cross-check of external fragments

Pipeline (every step recorded in the manifest):
  1. collect candidates
       A  controlled : the 15 Review-1 programs (imported unchanged) +
                       template programs (benchmarks/templates.py)
       B  randomized : grammar-based random programs (benchmarks/randomgen.py)
       C  external   : conservative C -> MiniArith extraction from jotai_unique_300/
                       (benchmarks/external.py); incompatible files are kept as records
  2. validate each candidate: parse, compile to TAC, run the fixture tests on the
     AST reference interpreter (expected outputs), the TAC interpreter and the
     compiled-Python backend; all three must agree; apply rejection rules
  3. deduplicate (benchmarks/dedup.py): normalised source and canonical TAC
  4. write manifest.jsonl (one record per candidate, accepted or not),
     dedup_report.json, statistics.json + CSVs, build_info.json

Everything except build_info.json is a deterministic function of the config
(and, for group C, of the presence of gcc).
"""

