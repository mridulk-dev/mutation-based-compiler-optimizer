"""Render docs/results.md from saved artifacts (no number is typed by hand).

    python -m experiments.report                  # results/final -> docs/results.md
    python -m experiments.report results/quick docs/results_quick.md
"""

import csv
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = {"unoptimized": "Unoptimized", "fixed": "Fixed pipeline", "greedy": "Greedy", "beam": "Beam (w=4)",
         "greedy_noM8": "Greedy w/o M8"}
GROUPS = {"controlled": "A controlled", "randomized": "B randomized", "external": "C external"}
ORDER = ["unoptimized", "fixed", "greedy", "beam", "greedy_noM8"]


def load(path):
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def md_table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---:" if i else "---" for i in range(len(headers))) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def f(x, d=3):
    return "–" if x is None else f"{x:.{d}f}"


def sp(x, d=1):
    return "–" if x is None else f"{x:+.{d}f}%"


def examples(res_dir, ids):
    path = os.path.join(res_dir, "steps.jsonl")
    if not os.path.exists(path):
        return ""
    steps = {}
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            s = json.loads(line)
            if s["program_id"] in ids:
                steps[(s["program_id"], s["strategy"])] = s
    out = []
    for pid in ids:
        u, g = steps.get((pid, "unoptimized")), steps.get((pid, "greedy"))
        if not u or not g:
            continue
        out.append(f"### {pid}\n")
        out.append("Naive TAC → greedy-optimised TAC; accepted transformations in order:\n")
        out.append("```text\n" + "\n".join(f"{i + 1:2d}. {x['op_id']:<4} {x['description']}" for i, x in enumerate(g["steps"]))
                   + "\n```\n")
        left, right = u["optimized_tac"].split("\n"), g["optimized_tac"].split("\n")
        w = max(len(x) for x in left) + 4
        rows = [f"{'ORIGINAL':<{w}}OPTIMISED"] + [f"{(left[i] if i < len(left) else ''):<{w}}{right[i] if i < len(right) else ''}"
                                                 for i in range(max(len(left), len(right)))]
        out.append("```text\n" + "\n".join(rows) + "\n```\n")
    return "\n".join(out)


def render(res_dir):
    s = load(os.path.join(res_dir, "summary.json"))
    ve = load(os.path.join(res_dir, "validator_eval.json"))
    vs = load(os.path.join(res_dir, "verification_summary.json"))
    ds = load(os.path.join(ROOT, "dataset", "miniarith-v1", "statistics.json"))
    if not s:
        raise SystemExit(f"no summary.json in {res_dir}")
    rel = os.path.relpath(res_dir, ROOT).replace("\\", "/")
    L = [f"# Results\n\n_Generated by `python -m experiments.report` from `{rel}/` — do not edit by hand._\n"]
    env = s["environment"]
    L.append(f"Run: {s['dataset']['programs']} accepted programs from `{s['dataset']['manifest']}` "
             f"(manifest SHA-256 `{s['dataset']['manifest_sha256'][:16]}…`), Python {env['python']} "
             f"({env['implementation']}) on {env['platform']}, {env['cpu_count']} logical CPUs, git commit "
             f"`{(env.get('commit') or '?')[:10]}`{' (uncommitted changes present)' if env.get('dirty_worktree') else ''}. "
             f"Search + checks took {s['seconds']['search_and_checks']} s, the whole run {s['seconds']['total']} s.\n")

    c = s["correctness"]
    L.append("## 1. Correctness\n")
    L.append(f"**{c['correct_rows']} of {c['rows']}** (program, strategy) results are correct: they pass the fixture "
             f"tests, match the AST reference on {s['config']['heldout_inputs']} held-out inputs, and the compiled "
             f"backend agrees. Crashes: {c['crashes']}. Timeouts: {c['timeouts']}. Budget stops: {c['budget_stops']}.\n")
    L.append(md_table(["Strategy", "Results", "Correct", "Fixture tests passed", "Held-out matches", "Compiled-backend matches",
                       "Candidates rejected by validator"],
                      [[NAMES.get(k, k), v["results"], v["correct"], f"{v['fixture_tests_passed']}/{v['fixture_tests']}",
                        f"{v['heldout_matching']}/{v['heldout_checks']}", f"{v['compiled_matching']}/{v['heldout_checks']}",
                        v["candidates_rejected_by_validator"]] for k, v in ((k, c["by_strategy"][k]) for k in ORDER if k in c["by_strategy"])]))
    L.append("\nSafe operators produced no invalid candidates (rejections = 0). The validator therefore never had to "
             "filter out a wrong candidate during these runs, so correctness rests on operator soundness, which is "
             "covered by separate tests.\n")
    if vs:
        L.append(f"Reproducibility pipeline (`reproduce.py`, {vs['mode']} mode): "
                 f"**{'all steps passed' if vs['passed'] else 'SOME STEPS FAILED'}**.\n")
        L.append(md_table(["Step", "Status", "Seconds", "Detail"],
                          [[x["name"], x["status"], x["seconds"], x["detail"].replace("|", "/")] for x in vs["steps"]]))
        L.append("")

    if ve:
        L.append("### Validator self-evaluation (injected faults)\n")
        rows = []
        for proto in ("review1", "v2"):
            v = ve[proto]
            t = v["totals"]
            rows.append([v["protocol"], v["mutants"], t.get("rejected", 0), t.get("accepted_equivalent", 0),
                         t.get("accepted_but_different", 0), f"{100 * v['detection_rate_on_nonequivalent']:.2f}%"])
        L.append(md_table(["Protocol", "Mutants", "Rejected", "Accepted, equivalent on held-out", "Missed", "Detection"], rows))
        b = ve["blind_spot_demo"]
        L.append(f"\nAll experiments use protocol v2. A constructed blind spot (a mutant that fails only at "
                 f"a = {b['mutant_traps_only_at']}) is accepted by the validator: `{b['validator_accepts_mutant']}`. "
                 "Finite testing is not proof. \"Equivalent on held-out\" means no difference was found on 300 inputs; "
                 "it is not proven equivalence.\n")
        kinds = ve["v2"]["by_kind"]
        L.append(md_table(["Fault kind (v2)", "Rejected", "Accepted-equivalent", "Missed"],
                          [[k, v.get("rejected", 0), v.get("accepted_equivalent", 0), v.get("accepted_but_different", 0)]
                           for k, v in kinds.items()]))
        L.append("")

    L.append("## 2. Optimisation results (simulated cost model)\n")
    L.append("Final cost is relative to the unoptimised TAC (= 1.0); lower is better. Δ columns give the mean "
             "per-program change. Simulated cycles come from the cycle model, not hardware.\n")
    hdr = ["Strategy", "n", "Mean cost", "Median", "P10–P90", "Improved", "Worse than unopt.", "Δ instr", "Δ arith",
           "Δ temps", "Δ sim. cycles", "Evals / program", "Search s (total)"]

    def row(k, v):
        return [NAMES.get(k, k), v["programs"], f(v["mean_final_cost"], 4), f(v["median_final_cost"], 4),
                f"{f(v['p10_final_cost'])}–{f(v['p90_final_cost'])}", v["programs_improved"],
                v["programs_worse_than_unoptimized"], sp(v["mean_instructions_change_pct"]),
                sp(v["mean_arith_ops_change_pct"]), sp(v["mean_temps_change_pct"]), sp(v["mean_cycles_change_pct"]),
                f(v["mean_candidates_evaluated"], 0), f(v["total_search_seconds"], 1)]

    L.append("### All groups (shown for reference only; per-group tables below)\n")
    L.append(md_table(hdr, [row(k, s["overall"][k]) for k in ORDER if k in s["overall"]]))
    for g in s["by_group"]["greedy"]:
        L.append(f"\n### Group {GROUPS.get(g, g)}\n")
        L.append(md_table(hdr, [row(k, s["by_group"][k][g]) for k in ORDER if k in s["by_group"] and g in s["by_group"][k]]))
    L.append("\n### By category (mean final cost)\n")
    cats = list(s["by_category"]["greedy"])
    L.append(md_table(["Group/category", "n", "Fixed", "Greedy", "Beam", "Greedy w/o M8"],
                      [[cat, s["by_category"]["greedy"][cat]["programs"]] +
                       [f(s["by_category"][k][cat]["mean_final_cost"], 4) for k in ("fixed", "greedy", "beam", "greedy_noM8")]
                       for cat in cats]))
    L.append("\n### Per-program comparisons (win / tie / loss, no averaging)\n")
    L.append(md_table(["A", "B", "Metric", "A better", "Tie", "A worse", "Mean Δ (A−B)", "Programs where A is worse (first 10)"],
                      [[NAMES.get(x["a"], x["a"]), NAMES.get(x["b"], x["b"]), x["metric"], x["a_better"], x["tie"],
                        x["a_worse"], f(x["mean_difference"], 5), ", ".join(x["a_worse_programs"][:10]) or "–"]
                       for x in s["comparisons"]]))
    for g, cs in s.get("comparisons_by_group", {}).items():
        L.append(f"\n{GROUPS.get(g, g)}: " + "; ".join(f"{NAMES[x['a']]} vs {NAMES[x['b']]}: better {x['a_better']}, "
                                                        f"tie {x['tie']}, worse {x['a_worse']}" for x in cs) + ".")
    L.append("")

    if s.get("sensitivity"):
        L.append("## 3. Cost-weight sensitivity\n")
        L.append(md_table(["Weights (I/A/T/C)", "Fixed mean cost", "Greedy mean cost", "Greedy better / tie / worse vs fixed",
                           "Greedy Δ instr", "Greedy Δ temps", "Greedy Δ sim. cycles", "Same direction as baseline", "Correct"],
                          [[f"{k} ({'/'.join(str(x) for x in s['config']['weight_configs'][k].values())})",
                            f(v["fixed_mean_cost"], 4), f(v["greedy_mean_cost"], 4),
                            f"{v['greedy_better']} / {v['tie']} / {v['greedy_worse']}", sp(v["greedy_mean_instructions_change_pct"]),
                            sp(v["greedy_mean_temps_change_pct"]), sp(v["greedy_mean_cycles_change_pct"]),
                            "yes" if v["direction_same_as_baseline"] else "**no**", f"{v['correct']}/{v['results']}"]
                           for k, v in s["sensitivity"].items()]))
        L.append("\nWeighted costs from different rows are not comparable; the raw metric changes are.\n")

    t = s.get("timing")
    if t:
        L.append("## 4. Measured wall-clock time\n")
        L.append(f"Protocol: {s['config']['timing']['warmup']} warm-up runs, {s['config']['timing']['repeats']} interleaved "
                 f"repeats per variant, GC disabled, batch = error-free fixture inputs. {t['classification_rule']}.\n")
        for be, label in (("interp", "Python TAC interpreter"), ("compiled", "TAC compiled to Python")):
            if be not in t:
                continue
            L.append(f"### {label}\n")
            L.append(md_table(["Strategy", "Geomean speed-up", "Median", "P10–P90", "Improved", "Inconclusive", "Regressed",
                               "Geomean by group"],
                              [[NAMES.get(k, k), f"{v['geomean_speedup_vs_unoptimized']:.3f}×", f"{v['median_speedup_vs_unoptimized']:.3f}×",
                                f"{v['p10_speedup']:.2f}–{v['p90_speedup']:.2f}", v["improved"], v["inconclusive"], v["regressed"],
                                ", ".join(f"{GROUPS.get(g, g)} {x:.2f}×" for g, x in v["geomean_speedup_by_group"].items())]
                               for k, v in t[be]["per_strategy"].items()]))
            rc = t[be]["reordering_check"]
            L.append(f"\nSpearman ρ: simulated cycles vs measured time = {t[be]['spearman_cycles_vs_time']}, "
                     f"instruction count vs measured time = {t[be]['spearman_instructions_vs_time']} "
                     f"({t[be]['points']} points). Reordering check: in {rc['programs']} programs where greedy and "
                     f"greedy w/o M8 differ in simulated cycles, the variant with fewer simulated cycles was also "
                     f"faster in {rc['agreements']} ({'–' if rc['agreement_rate'] is None else f'{100 * rc['agreement_rate']:.0f}%'}).\n")
        L.append("Interpretation guide: speed-ups are relative to deliberately naive TAC and measured on Python "
                 "executors, so they mostly reflect fewer executed instructions. They say nothing about native code. "
                 "A reordering agreement rate near 50% means the stall term of the cycle model has no measurable "
                 "counterpart on these executors.\n")

    if ds:
        L.append("## 5. Dataset used\n")
        L.append(md_table(["Group", "Accepted", "Rejected", "Duplicate", "Incompatible"],
                          [[GROUPS.get(g, g), v["accepted"], v["rejected"], v["duplicate"], v["incompatible"]]
                           for g, v in ds["by_group"].items()]))
        L.append("\nSee `dataset/README.md` for provenance, licensing and rejection reasons.\n")

    L.append("## 6. Representative before/after TAC\n")
    L.append(examples(res_dir, ["P13", "SYN-CSE-012", "RND-0007", "EXT-JOTAI-158"]))
    L.append("\n## Plots\n")
    idx = load(os.path.join(res_dir, "plots", "index.json")) or {}
    for name, meta in idx.items():
        L.append(f"- `{rel}/plots/{name}`: {meta['description']} (data: {', '.join(meta['sources'])})")
    return "\n".join(L) + "\n"


def main(argv=None):
    argv = argv if argv is not None else sys.argv[1:]
    res_dir = argv[0] if argv else os.path.join(ROOT, "results", "final")
    out = argv[1] if len(argv) > 1 else os.path.join(ROOT, "docs", "results.md")
    text = render(res_dir)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
